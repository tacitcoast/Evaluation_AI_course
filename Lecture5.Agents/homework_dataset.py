def _rows(items, test_type):
    out = []
    for question, expected, tools, urls in items:
        out.append({
            "question": question,
            "expected_response": expected,
            "expected_tools": ", ".join(tools),
            "urls": " | ".join(urls),
            "test_type": test_type,
        })
    return out


