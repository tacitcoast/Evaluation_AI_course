META_EXPECTED = {
    "фильтр по цене": "Объявления с ценой ниже 2 млн дирхамов",
    "средняя цена": "Средняя цена объявлений в злотых",
    "перевод в рубли": "Цены позиций, пересчитанные в рубли",
}


def build():
    happy = pd.DataFrame(_rows(HAPPY, "happy_path"))
    negative = pd.DataFrame(_rows(NEGATIVE, "negative"))

    meta_rows = []
    for question, tools, urls, group in META:
        meta_rows.append({
            "question": question,
            "expected_response": META_EXPECTED[group],
            "expected_tools": ", ".join(tools),
            "urls": " | ".join(urls),
            "test_type": "metamorphic",
            "metamorphic_group": group,
        })
    meta = pd.DataFrame(meta_rows)
    return happy, negative, meta


def save(out_dir="data"):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    happy, negative, meta = build()

    files = {
        "homework_happy_path": happy,
        "homework_negative": negative,
        "homework_metamorphic": meta,
    }
    for name, df in files.items():
        df.to_excel(out / f"{name}.xlsx", index=False)
        df.to_csv(out / f"{name}.csv", index=False)
        print(f"{name}: {len(df)} строк")

    full = pd.concat([happy, negative, meta], ignore_index=True)
    full.to_excel(out / "homework_dataset_full.xlsx", index=False)
    full.to_csv(out / "homework_dataset_full.csv", index=False)
    print(f"homework_dataset_full: {len(full)} строк")

    print("\nРаспределение по инструментам:")
    counts = {}
    for value in full["expected_tools"]:
        for tool in [t.strip() for t in str(value).split(",") if t.strip()]:
            counts[tool] = counts.get(tool, 0) + 1
    for tool, n in sorted(counts.items(), key=lambda kv: -kv[1]):
        print(f"  {tool}: {n}")
    print(f"  без инструментов: {sum(1 for v in full['expected_tools'] if not str(v).strip())}")

    print("\nСсылки в датасете:")
    links = {}
    for value in full["urls"]:
        for url in [u.strip() for u in str(value).split("|") if u.strip()]:
            links[url] = links.get(url, 0) + 1
    for url, n in sorted(links.items(), key=lambda kv: -kv[1]):
        print(f"  {n:>3}  {url}")


if __name__ == "__main__":
    save("data")
